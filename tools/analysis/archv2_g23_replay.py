import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from archv2_arena import ro  # noqa: E402

ro.install_global_guard()
from archv2_arena import cert, data, g23, report  # noqa: E402
from archv2_arena.streams import Streams  # noqa: E402
import archv2_g22_sim as g22cli  # noqa: E402  (header / input lines / identity; its import installs nothing new)

REC_MASTER = "ARCHV2-G23-REC-1"
MODULES_G23 = ("archv2_g23_replay.py", "archv2_arena/g23.py", "archv2_arena/selftest_g23.py")


def paths_for(which):
    return dict(eval=data.path("eval"), cache=data.path(which), snapshots=data.path("snapshots"),
                promoted=data.path("promoted"), root=data.DATA_ROOT)


def exact_board(sb, which, say, streams):
    import rubric_p8 as p8
    board, has_votes, snap = g23.load_v2(paths_for(which), sorted(p8.ARENA12), which)
    edges, aq = data.edges_exact(board, B=sb.B, floor=200, streams=streams)
    data.mark_established(edges, board.K, aq, sb)
    say("  board %s: %d valid verdicts, anchors %d, edges %d (established %d); per-order votes %s; builder EXACT"
        " (build()'s loop, Random(42), rj.mm_fit)" % (which, board.n_valid, len(aq), len(edges),
                                                     sum(1 for e in edges if e["est"]), "yes" if has_votes else "NO"))
    return board, edges, aq, has_votes


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--leg", choices=("identity", "certab", "conjuncts", "residue", "holm", "mcstreams"))
    ap.add_argument("--out")
    ap.add_argument("--master", default=REC_MASTER)
    ap.add_argument("--dev", action="store_true", help="a run that is NOT of record (any master)")
    ap.add_argument("--board", default="grok", choices=("grok", "x12"))
    ap.add_argument("--mistral", default="x12", choices=("x12", "merged"))
    ap.add_argument("--tables-dir")
    ap.add_argument("--B", type=int, default=300)
    ap.add_argument("--S", type=int, default=5)
    a = ap.parse_args(argv)
    if a.selftest:
        from archv2_arena import selftest_g23
        return selftest_g23.run()
    if not a.leg or not a.out:
        ap.error("--leg and --out are required (write-once; nothing here is of record)")
    if a.master != REC_MASTER and not a.dev:
        report.hit("RECORD.REFUSED_MASTER")
        raise SystemExit("[G23] --master %r is not the registered ARCHV2-G23-REC-1 (d6129cf): refused (use --dev for a run"
                         " that is not of record)" % a.master)
    a.R, a.r_registration, a.dry_run = None, None, False
    a.rec_master, a.reg_name = REC_MASTER, "ARCH-V2-G23"
    out = report.Out(a.out)
    streams = Streams(a.master)
    sb = data.import_sb()
    say = out
    g22cli.header(say, a, needs_pool=True)
    say("  G23 modules:")
    for m in MODULES_G23:
        i = data.file_identity(os.path.join(HERE, m))
        say("    %-34s blob:%s sha256-lf16:%s (%s)" % (m, i["blob"], i["sha256_lf16"], i["worktree"]))
    if a.leg == "identity":
        p = paths_for(a.board)
        say(*g22cli.input_lines([p["eval"], p["cache"], p["snapshots"]]))
        rec = os.path.join(data.DATA_ROOT, data.X12DIR, "grok_calib_systematic_budget.txt" if a.board == "grok" else "systematic_budget.txt")
        say("  recorded table: %s" % rec)
        r = g23.identity_leg(say, sb, p, recorded_table=rec, record=g23.RECORD if a.board == "grok" else {"f": {}, "u": {}},
                             tables_dir=a.tables_dir, streams=streams)
        if a.board != "grok":
            say("  (the record's GROK-CALIB integers do not apply to %s; the integer check ran on an empty target set)" % a.board)
    elif a.leg == "certab":
        say(*g22cli.input_lines([data.path("grok"), data.path("kotlin"), data.path("eval")]))
        _, eg, _, _ = exact_board(sb, "grok", say, streams)
        _, ek, _, _ = exact_board(sb, "kotlin", say, streams)
        g23.certab_leg(say, sb, [("GROK-CALIB", eg), ("Kotlin", ek)])
    elif a.leg == "conjuncts":
        say(*g22cli.input_lines([data.path("grok"), data.path("eval")]))
        board, eg, _, has_votes = exact_board(sb, "grok", say, streams)
        report.need(has_votes, "the grok cache carries no per-order votes; the per-order conjunct cannot run")
        g23.conjuncts_leg(say, sb, board, eg, streams, B=a.B)
    elif a.leg == "residue":
        say(*g22cli.input_lines([data.path("grok"), data.path("x12"), data.path("eval")] + ([data.path("x20")] if a.mistral == "merged" else [])))
        _, eg, _, _ = exact_board(sb, "grok", say, streams)
        if a.mistral == "x12":
            _, em, _, _ = exact_board(sb, "x12", say, streams)
        else:
            # ruling B (4b25059): on merged the EXACT builder (Random(42), rj.mm_fit) is required for the precondition
            board, kt, snap, paths = g22cli.load_board("merged")
            em, aq = data.edges_exact(board, B=sb.B, floor=200, streams=streams)
            data.mark_established(em, board.K, aq, sb)
            say("  merged Mistral board: EXACT builder (build()'s loop, Random(42), rj.mm_fit), %d edges" % len(em))
        rr = g23.residue_leg(say, sb, em, eg, "Mistral-" + a.mistral, "grok", mistral_key=a.mistral, builder="exact")
        if rr["word"].startswith("FAILED PRECONDITION"):
            # READY 5dfc825 D6: a failed precondition exits non-zero; the output name carries it
            out.path = out.path + ".FAILED-PRECONDITION.txt"
            say("", "  FAILED PRECONDITION (ruling B): the residue is NOT read; exit 2")
            say(*ro.log_lines())
            print("[G23] written: %s" % out.write(streams))
            return 2
    elif a.leg == "holm":
        say(*g22cli.input_lines([data.path("grok"), data.path("eval")]))
        board, eg, aq, _ = exact_board(sb, "grok", say, streams)
        A = cert.loao_v(cert.EdgeArrays(eg), fit=g23.exact_fit(sb))
        called = {(e["anchor"], e["a"], e["b"]) for e, c in zip(eg, A["called"]) if c}
        g23.holm_leg(say, sb, eg, board.K, aq, called)
    elif a.leg == "mcstreams":
        say(*g22cli.input_lines([data.path("grok"), data.path("eval")]))
        import rubric_p8 as p8
        board, _, _ = g23.load_v2(paths_for("grok"), sorted(p8.ARENA12), "grok")
        g23.mcstreams_leg(say, board, streams, S=a.S, B=a.B)
    say("", "  EXECUTION WITNESS (new code paths): %s" % dict(sorted(data.WITNESS.items())))
    say(*ro.log_lines())
    say(*streams.summary())
    print("[G23] written: %s" % out.write(streams))
    return 0


if __name__ == "__main__":
    sys.exit(main())
