"""Regenerate docs/agents/results/INDEX.md from the per-experiment records docs/agents/results/<ID>.json.

The records are the machine-readable face of the programme (docs/judge_v2_program.md) and the ledger
(docs/test_ledger.html); they are written by the registrar and read by every other agent. This script
computes nothing: it validates each record against the fixed key set and renders the index.

    python tools/analysis/results_index.py            # validate + write INDEX.md
    python tools/analysis/results_index.py --check    # validate only, exit 3 on a defect
    python tools/analysis/results_index.py --selftest

Zero calls, no DB, reads and writes only under docs/agents/results/.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "docs" / "agents" / "results"
INDEX = RESULTS / "INDEX.md"

REQUIRED = [
    "id", "title", "question", "kind", "state", "registration", "script", "ready", "go", "run", "review",
    "criteria", "predictions", "falsifier", "numbers_of_record", "sentence_of_record", "chips", "brackets",
    "does_not_show", "ledger", "depends_on", "supersedes", "superseded_by", "closed_line", "sources",
    "last_update",
]
KINDS = {"zero-call", "build", "judged", "solve", "engineering"}
STATES = {"drafted", "registered", "built", "READY", "running", "paused", "run-unreviewed", "done",
          "UNDETERMINED", "declined", "withdrawn", "blocked"}
SCORES = {"HELD", "FAILED", "UNDETERMINED", "PARTIAL", "SILENT", "DELIVERED", "n/a"}   # PARTIAL: a registered branch (e.g. T1B A2), 2026-09-23


def validate(rec: dict, path: Path) -> list[str]:
    errs = []
    for k in REQUIRED:
        if k not in rec:
            errs.append(f"{path.name}: missing key {k}")
    if errs:
        return errs
    if rec["id"] != path.stem:
        errs.append(f"{path.name}: id {rec['id']!r} != file stem")
    if rec["kind"] not in KINDS:
        errs.append(f"{path.name}: kind {rec['kind']!r} not in {sorted(KINDS)}")
    if rec["state"] not in STATES:
        errs.append(f"{path.name}: state {rec['state']!r} not in {sorted(STATES)}")
    for fam in ("criteria", "predictions"):
        for c in rec[fam]:
            for k in ("id", "text", "result"):
                if k not in c:
                    errs.append(f"{path.name}: {fam} item missing {k}")
            if c.get("result") not in SCORES:
                errs.append(f"{path.name}: {fam} {c.get('id')} result {c.get('result')!r} not in {sorted(SCORES)}")
    for b in rec["brackets"]:
        for k in ("date", "by", "text"):
            if k not in b:
                errs.append(f"{path.name}: bracket missing {k}")
    if rec["state"] in {"done", "UNDETERMINED"}:
        if not rec["run"] or not rec["run"].get("outcome_file"):
            errs.append(f"{path.name}: state {rec['state']} without run.outcome_file")
        if not rec["review"]:
            errs.append(f"{path.name}: state {rec['state']} without a review")
        if not rec["sentence_of_record"]:
            errs.append(f"{path.name}: state {rec['state']} without sentence_of_record")
    if not rec["sources"]:
        errs.append(f"{path.name}: sources empty (every value must name where it was copied from)")
    return errs


def load(results: Path = RESULTS) -> tuple[list[dict], list[str]]:
    recs, errs = [], []
    for p in sorted(results.glob("*.json")):
        try:
            rec = json.loads(p.read_text(encoding="utf-8"))
        except json.JSONDecodeError as e:
            errs.append(f"{p.name}: invalid JSON ({e})")
            continue
        errs.extend(validate(rec, p))
        recs.append(rec)
    return recs, errs


def render(recs: list[dict]) -> str:
    lines = [
        "# Experiment records index",
        "",
        "Generated by `python tools/analysis/results_index.py` from `docs/agents/results/<ID>.json`; do not edit by hand.",
        "One record per experiment; the record is the machine-readable face of the programme and the ledger and is kept by the registrar.",
        "",
        "| id | state | kind | verdict / sentence of record | ledger row | last update |",
        "|---|---|---|---|---|---|",
    ]
    order = {s: i for i, s in enumerate(["running", "READY", "built", "registered", "drafted", "paused", "blocked",
                                          "run-unreviewed", "done", "UNDETERMINED", "declined", "withdrawn"])}
    for r in sorted(recs, key=lambda r: (order.get(r["state"], 99), -str(r["last_update"]).__hash__() * 0, r["id"])):
        sent = (r["sentence_of_record"] or "").replace("|", "\\|")
        if len(sent) > 160:
            sent = sent[:157] + "..."
        led = r["ledger"] or {}
        row = led.get("row_id", "") if isinstance(led, dict) else ""
        lines.append(f"| {r['id']} | {r['state']} | {r['kind']} | {sent} | {row} | {r['last_update']} |")
    lines.append("")
    lines.append(f"{len(recs)} records.")
    return "\n".join(lines) + "\n"


def selftest() -> int:
    import tempfile; import scratch_dir  # TEMP-SPRAWL: temp on E:, removed at exit
    good = {k: None for k in REQUIRED}
    good.update(id="T1", title="t", question="q", kind="judged", state="registered",
                registration={"commit": "abc", "program_lines": "L1-L2", "date": "2026-09-19"},
                script={"path": "tools/analysis/x.py", "sha16": "0" * 16, "commit": "abc"},
                go="n/a", criteria=[{"id": "C1", "text": "x", "result": "n/a"}], predictions=[],
                falsifier={"text": "f", "fired": False}, numbers_of_record={}, chips=[], brackets=[],
                does_not_show=[], depends_on=[], sources=["docs/judge_v2_program.md L1-L2"],
                last_update="2026-09-19", closed_line=False, sentence_of_record="")
    with tempfile.TemporaryDirectory() as d:
        dd = Path(d)
        (dd / "T1.json").write_text(json.dumps(good), encoding="utf-8")
        recs, errs = load(dd)
        # every check below raises explicitly, never `assert`: the selftest must hold under python -O
        # (RESULTS-INDEX-SELFTEST-ASSERTS, 2026-09-23; the checks pre-dating c33b404 were asserts and vanished under -O)
        if errs:
            raise SystemExit("SELFTEST FAIL: a well-formed record was rejected: %r" % errs)
        bad = dict(good, id="T2", state="done")
        (dd / "T2.json").write_text(json.dumps(bad), encoding="utf-8")
        recs, errs = load(dd)
        if not any("without run.outcome_file" in e for e in errs):
            raise SystemExit("SELFTEST FAIL: a done record without run.outcome_file was accepted: %r" % errs)
        if not any("without a review" in e for e in errs):
            raise SystemExit("SELFTEST FAIL: a done record without a review was accepted: %r" % errs)
        bad3 = dict(good, id="T3", kind="magic")
        (dd / "T3.json").write_text(json.dumps(bad3), encoding="utf-8")
        _, errs = load(dd)
        if not any("kind 'magic'" in e for e in errs):
            raise SystemExit("SELFTEST FAIL: an unknown kind was accepted: %r" % errs)
        # the score vocabulary, both directions (explicit raises, not assert: they must hold under python -O)
        ok4 = dict(good, id="T4", criteria=[{"id": "C1", "text": "x", "result": "PARTIAL"}])
        (dd / "T4.json").write_text(json.dumps(ok4), encoding="utf-8")
        _, errs = load(dd)
        if any("T4.json" in e for e in errs):
            raise SystemExit("SELFTEST FAIL: PARTIAL (a registered outcome word) was rejected: %r" % errs)
        bad5 = dict(good, id="T5", criteria=[{"id": "C1", "text": "x", "result": "MAYBE"}])
        (dd / "T5.json").write_text(json.dumps(bad5), encoding="utf-8")
        _, errs = load(dd)
        if not any("result 'MAYBE'" in e for e in errs):
            raise SystemExit("SELFTEST FAIL: an unregistered result word was accepted: %r" % errs)
        text = render(recs)
        if "| T1 | registered |" not in text:
            raise SystemExit("SELFTEST FAIL: render() lacks the T1 row: %r" % text)
    print("SELFTEST PASS (results_index: required keys, kinds, states, scores both ways, done needs outcome+review, render)")
    return 0


def main(argv: list[str]) -> int:
    if "--selftest" in argv:
        return selftest()
    RESULTS.mkdir(parents=True, exist_ok=True)
    recs, errs = load()
    for e in errs:
        print("DEFECT", e)
    if errs and "--check" in argv:
        return 3
    if "--check" in argv:
        print(f"OK {len(recs)} records")
        return 0
    if errs:
        print("INDEX not written: fix the defects above")
        return 3
    INDEX.write_text(render(recs), encoding="utf-8", newline="\n")
    print(f"wrote {INDEX} ({len(recs)} records)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
