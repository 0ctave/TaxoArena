def v1_readout(sb, edges, K, anchor_qs, gap=None):
    """The record's integers from `edges` through the NEW LOAO driver with the fit of record."""
    gap = sb.GAP if gap is None else gap
    fit = exact_fit(sb)
    out = {}
    for tag, es in (("f", [e for e in edges if e["gap"] >= gap]), ("u", list(edges))):
        E = cert.EdgeArrays(es)
        b0, b1 = sb.fit(es)
        rc = cert.craw_v(E.p) >= cert.THRESH
        est_list = sb.established(es, K, anchor_qs)
        est_ids = {id(e) for e in est_list}
        for e in es:
            e["est"] = id(e) in est_ids
        E = cert.EdgeArrays(es)
        L = cert.loao_v(E, x0=(b0, b1), fit=fit)
        data.WITNESS["g23.loao_folds"] += len(L["fold_params"])
        e0, e1 = sb.fit(est_list, x0=(b0, b1))
        null = minimize_scalar(lambda x: sb.nll((x, 0.0), est_list), bounds=(-12, 4), method="bounded")
        ddev = 2 * (null.fun - sb.nll((e0, e1), est_list))
        out[tag] = dict(n=len(es), raw_called=int(rc.sum()), raw_wrong=int((rc & ~E.right).sum()), b0="%+.4f" % b0,
                        b1="%+.4f" % b1, loao_called=L["n_called"], loao_wrong=L["wrong"], loao_wrong_est=L["wrong_est"],
                        loao_nominal="%.2f" % L["nominal"], est=len(est_list), b1_est="%+.4f" % e1, ddev="%.2f" % ddev)
    return out


def split_crit1(lines):
    try:
        i = next(k for k, s in enumerate(lines) if s.startswith(CRIT1_START))
        j = next(k for k, s in enumerate(lines) if s.startswith(CRIT1_END))
    except StopIteration:
        return None
    return lines[:i], lines[i:j], lines[j:]


