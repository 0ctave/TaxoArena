def cert_ab(sb, edges, label, fit=None):
    E = cert.EdgeArrays(edges)
    fit = fit or exact_fit(sb)
    A = cert.loao_v(E, fit=fit)
    Bg = cert.gate_loao(E)
    table = cert.gate_fit(E)
    rc = cert.craw_v(E.p) >= cert.THRESH
    b0, b1 = A["b0"], A["b1"]
    est = E.subset(E.est)
    e1, dd, _ = cert.ddev_v(est, x0=(b0, b1), fit=fit) if len(est) >= 20 else (float("nan"),) * 3
    keys = [(e["anchor"], e["a"], e["b"]) for e in edges]
    return dict(label=label, n=len(E), raw=(int(rc.sum()), int((rc & ~E.right).sum()), int((rc & ~E.right & E.est).sum())),
                A=A, B=Bg, table=table, b0=b0, b1=b1, b1_est=e1, ddev=dd,
                A_called={k for k, c in zip(keys, A["called"]) if c}, B_called={k for k, c in zip(keys, Bg["called"]) if c})


def falsifier_words(name, called, wrong_est, ref_wrong_est, ref_name, n, util_bar=0.60):
    """G23's falsifier, read for one certificate: utility over ALL edges against the bar, and wrong(established) against
    a reference (A against raw: it cannot rise, the widener only removes calls; B against A)."""
    u = called / max(1, n)
    f1 = ("UTILITY BELOW %.0f%% OF ALL EDGES (%.1f%%)" % (100 * util_bar, 100 * u) if u < util_bar
          else "utility at or above %.0f%% (%.1f%%)" % (100 * util_bar, 100 * u))
    rises = wrong_est > ref_wrong_est
    f2 = ("wrong(established) RISES vs %s (%d > %d)" if rises else "wrong(established) does not rise vs %s (%d <= %d)") % (
        ref_name, wrong_est, ref_wrong_est)
    hit("CERTAB.%s.%s" % (name, "UTIL_BELOW" if u < util_bar else "UTIL_OK"))
    hit("CERTAB.%s.%s" % (name, "RISES" if rises else "NO_RISE"))
    return f1, f2


def b_admissible(a_wrong_est, b_wrong_est, b_called, n, util_bar=0.60):
    """The registered criterion (b) (d6129cf): B ADMISSIBLE iff its LOAO wrong(established) <= A's AND its utility
    >= util_bar of ALL edges."""
    u = b_called / max(1, n)
    ok = b_wrong_est <= a_wrong_est and u >= util_bar
    hit("CERTAB.B_%s" % ("ADMISSIBLE" if ok else "NOT_ADMISSIBLE"))
    return ("B ADMISSIBLE (wrong(established) %d <= A's %d; utility %.1f%% >= %.0f%%)" % (b_wrong_est, a_wrong_est, 100 * u, 100 * util_bar)
            if ok else "B NOT ADMISSIBLE (wrong(established) %d vs A's %d; utility %.1f%% vs the %.0f%% bar)"
            % (b_wrong_est, a_wrong_est, 100 * u, 100 * util_bar))


