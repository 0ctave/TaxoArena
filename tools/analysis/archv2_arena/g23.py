def logit_cluster(X, y, groups, iters=100):
    b = np.zeros(X.shape[1])
    for _ in range(iters):
        p = 1 / (1 + np.exp(-(X @ b)))
        H = X.T @ (X * (p * (1 - p))[:, None])
        step = np.linalg.solve(H + 1e-9 * np.eye(X.shape[1]), X.T @ (y - p))
        b = b + step
        if np.abs(step).max() < 1e-10:
            break
    p = 1 / (1 + np.exp(-(X @ b)))
    Hinv = np.linalg.inv(X.T @ (X * (p * (1 - p))[:, None]))
    sc = X * (y - p)[:, None]
    G = defaultdict(lambda: np.zeros(X.shape[1]))
    for s, g in zip(sc, groups):
        G[g] += s
    meat = sum(np.outer(v, v) for v in G.values())
    nG = len(G)
    V = Hinv @ meat @ Hinv * (nG / max(1, nG - 1))
    return b, np.sqrt(np.diag(V)), nG


def beta_len(board, floor=200):
    X, y, grp = [], [], []
    for anc in sorted(board.by):
        if len(board.by[anc]) < floor:
            continue
        for a, b, q, w in board.by[anc]:
            if w == "TIE":
                continue
            la, lb = board.L.get(q, {}).get(a), board.L.get(q, {}).get(b)
            ka, kb = board.K.get(q, {}).get(a), board.K.get(q, {}).get(b)
            if la is None or lb is None or ka is None or kb is None:
                continue
            X.append([1.0, (la - lb) / 1000.0, float(ka - kb)]); y.append(1.0 if w == a else 0.0); grp.append(q)
    need(len(y) >= 10, "too few decisive matches with lengths and key for beta_len")
    b, se, nG = logit_cluster(np.array(X), np.array(y), grp)
    return b[1], se[1], len(y), nG, b[2]


