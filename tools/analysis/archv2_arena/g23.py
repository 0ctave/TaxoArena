def exact_fit(sb):
    def f(E, x0=(-3.0, 3.0)):
        data.WITNESS["g23.exact_fit"] += 1
        return sb.fit(E.edges, x0=x0)
    return f


@contextlib.contextmanager
def recorded_env(sb, paths):
    """Point the RECORDED build() at the read-only loader's files: sqlite3 inside systematic_budget and rubric_512 is
    the ro.Shim, the eval / snapshots / promoted paths are the given ones, and the stack_judge stub serves the cache."""
    import rejudge_grok as rj
    import rubric_512 as r512
    saved = (sb.sqlite3, r512.sqlite3, rj.EVAL_DB, r512.SNAP_DB, r512.PROMOTED)
    shim = ro.Shim()
    sb.sqlite3 = shim; r512.sqlite3 = shim
    rj.EVAL_DB, r512.SNAP_DB, r512.PROMOTED = paths["eval"], paths["snapshots"], paths["promoted"]
    data.authorise_cache(paths["cache"])
    try:
        yield shim
    finally:
        sb.sqlite3, r512.sqlite3, rj.EVAL_DB, r512.SNAP_DB, r512.PROMOTED = saved
        data.authorise_cache(None)


