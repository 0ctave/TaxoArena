package taxonomy.dataset

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.boolean
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertNotEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test
import java.io.File

/**
 * Cross-language pin of the side function: every vector in
 * experiment_configs/split_function_vectors.json (generated by tools/analysis/split_side.py) must
 * reproduce here, byte for byte. This test is the independent replication of the Python module.
 */
class SplitSideVectorsTest {

    private val vectors = Json.parseToJsonElement(
        File("experiment_configs/split_function_vectors.json").also {
            assertTrue(it.isFile, "${it.path} not found; run from the repo root")
        }.readText()
    ).jsonObject

    @Test
    fun `constants match the vector file`() {
        assertEquals(SplitSide.NORMALISER_VERSION, vectors["normaliser_version"]!!.jsonPrimitive.content)
        assertEquals(SplitSide.KEY_RULE, vectors["key_rule"]!!.jsonPrimitive.content)
        assertEquals(SplitSide.SIDE_MODULUS, vectors["modulus"]!!.jsonPrimitive.int)
        assertEquals(SplitSide.EVAL_UPPER, vectors["eval_upper"]!!.jsonPrimitive.int)
        assertEquals(SplitSide.GATE_LOWER, vectors["gate_lower"]!!.jsonPrimitive.int)
        assertEquals(SplitSide.GATE_UPPER, vectors["gate_upper"]!!.jsonPrimitive.int)
        assertEquals(SplitSide.FIELD_SEP, vectors["field_sep"]!!.jsonPrimitive.content)
        assertEquals(SplitSide.OPTION_SEP, vectors["option_sep"]!!.jsonPrimitive.content)
        assertEquals(SplitSide.WHITESPACE_CLASS, vectors["whitespace_class"]!!.jsonPrimitive.content)
    }

    @Test
    fun `every vector reproduces content_key, stem_key, h and side`() {
        val cases = vectors["cases"]!!.jsonArray
        assertTrue(cases.size >= 12, "expected at least 12 vectors, found ${cases.size}")
        for (c in cases.map { it.jsonObject }) {
            val label = c["label"]!!.jsonPrimitive.content
            val stem = c["stem"]!!.jsonPrimitive.content
            val options = c["options"]!!.jsonArray.map { it.jsonPrimitive.content }
            val contract = c["contract_id"]!!.jsonPrimitive.content
            val family = c["family_id"]!!.let { if (it is kotlinx.serialization.json.JsonNull) null else it.jsonPrimitive.content }
            assertEquals(c["norm_stem"]!!.jsonPrimitive.content, SplitSide.norm(stem), "norm on $label")
            assertEquals(SplitSide.norm(stem), SplitSide.norm(SplitSide.norm(stem)), "norm not idempotent on $label")
            val ck = SplitSide.contentKey(stem, options, contract)
            assertEquals(c["content_key"]!!.jsonPrimitive.content, ck, "content_key on $label")
            val sk = SplitSide.stemKey(stem)
            assertEquals(c["stem_key"]!!.jsonPrimitive.content, sk, "stem_key on $label")
            assertEquals(c["stem_h"]!!.jsonPrimitive.int, SplitSide.sideHash(sk), "stem_h on $label")
            val h = SplitSide.sideHash(family ?: ck)
            assertEquals(c["h"]!!.jsonPrimitive.int, h, "h on $label")
            assertEquals(Side.valueOf(c["side"]!!.jsonPrimitive.content), SplitSide.sideOfHash(h), "side on $label")
            assertEquals(Side.valueOf(c["side"]!!.jsonPrimitive.content), SplitSide.tierB(family, ck), "tierB on $label")
        }
    }

    @Test
    fun `exactly one side for every hash value - gate and eval are disjoint by construction`() {
        var eval = 0; var gate = 0; var train = 0
        for (h in 0 until SplitSide.SIDE_MODULUS) {
            when (SplitSide.sideOfHash(h)) { Side.EVAL -> eval++; Side.GATE -> gate++; Side.TRAIN -> train++ }
        }
        assertEquals(SplitSide.EVAL_UPPER, eval)
        assertEquals(SplitSide.GATE_UPPER - SplitSide.GATE_LOWER, gate)
        assertEquals(SplitSide.SIDE_MODULUS - SplitSide.GATE_UPPER, train)
        assertEquals(SplitSide.SIDE_MODULUS, eval + gate + train)
    }

    @Test
    fun `option order does not change the key, the contract does`() {
        val a = SplitSide.contentKey("q", listOf("x", "y"), "c")
        val b = SplitSide.contentKey("q", listOf("y", "x"), "c")
        val c = SplitSide.contentKey("q", listOf("x", "y"), "d")
        assertEquals(a, b)
        assertNotEquals(a, c)
        assertNotEquals(SplitSide.contentKey("q", emptyList(), "c"), SplitSide.contentKey("q", listOf(""), "c"))
    }

    @Test
    fun `boundary vectors land on the registered bracket edges`() {
        val byLabel = vectors["cases"]!!.jsonArray.map { it.jsonObject }.associateBy { it["label"]!!.jsonPrimitive.content }
        fun side(label: String) = Side.valueOf(byLabel.getValue(label)["side"]!!.jsonPrimitive.content)
        assertEquals(Side.EVAL, side("boundary-299"))
        assertEquals(Side.GATE, side("boundary-300"))
        assertEquals(Side.GATE, side("boundary-399"))
        assertEquals(Side.TRAIN, side("boundary-400"))
        assertEquals(byLabel.getValue("nfc-composed")["content_key"], byLabel.getValue("nfd-decomposed")["content_key"])
    }

    @Test
    fun `tierA closes EVAL under content and gates only non-EVAL items`() {
        val pinnedIds = setOf(7)
        val evalText = "an arena question"
        val pinnedKeys = setOf(SplitSide.stemKey(evalText))
        assertEquals(Side.EVAL, SplitSide.tierA(pinnedIds, pinnedKeys, 7, SplitSide.stemKey("anything")))
        assertEquals(Side.EVAL, SplitSide.tierA(pinnedIds, pinnedKeys, -1_000_042, SplitSide.stemKey("  AN  arena question ")))
        // A non-pinned item lands on GATE or TRAIN, never EVAL.
        for (i in 0 until 200) {
            val s = SplitSide.tierA(pinnedIds, pinnedKeys, 100 + i, SplitSide.stemKey("train item $i"))
            assertNotEquals(Side.EVAL, s)
            val h = SplitSide.sideHash(SplitSide.stemKey("train item $i"))
            assertEquals(if (h in SplitSide.GATE_LOWER until SplitSide.GATE_UPPER) Side.GATE else Side.TRAIN, s)
        }
        val gate = SplitSide.gateOf((0 until 200).associate { it to "train item $it" })
        assertTrue(gate.all { SplitSide.tierA(pinnedIds, pinnedKeys, it, SplitSide.stemKey("train item $it")) == Side.GATE })
    }

    @Test
    fun `the stamp carries every constant and the pool`() {
        val s = SplitSide.stamp("p2dca21ab5f4ef3ae")
        assertEquals("norm-v1", s.normaliserVersion)
        assertEquals("p2dca21ab5f4ef3ae", s.poolId)
        assertTrue(s.sameFunctionAs(SplitSide.stamp(null)))
        assertTrue(!s.sameFunctionAs(s.copy(evalUpper = 100)))
        assertTrue(EpochGate.NONE.accept(emptySet()))
    }
}
