package taxonomy.service

import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.jsonObject
import org.junit.jupiter.api.Assertions.*
import org.junit.jupiter.api.Test
import taxonomy.operations.PythonJson

/**
 * PythonJson.dumps must produce the BYTES CPython's `json.dumps(value)` produces, because the recipe
 * payload's byte identity with the Python cache rests on it (ensure_ascii escaping of the ~24% of
 * rows with non-ASCII, the ", " / ": " separators, key order, int vs float rendering).
 * The cases (ASCII, em/en dash, CJK, an astral emoji -> surrogate pair, U+2028, DEL, control chars,
 * tab/newline/CR, quote, backslash, slash, NBSP, NUL; nested bodies with ints, floats, booleans, null)
 * were generated by `judge_wiring.py --gen-fixtures` with the real json.dumps.
 */
class PythonJsonDumpsTest {

    @Test
    fun `every fixture case serialises to the exact json dumps string`() {
        val cases = JudgeWiringFixtures.read("python_json_cases.json") as JsonArray
        assertTrue(cases.size >= 20, "fixture holds ${cases.size} cases")
        for (c in cases) {
            val o = c.jsonObject
            val value = JudgeWiringFixtures.toValue(o["value"]!!)
            val expected = JudgeWiringFixtures.str(o, "dumps")
            assertEquals(expected, PythonJson.dumps(value), "case value=${o["value"]}")
            assertArrayEquals(expected.toByteArray(Charsets.US_ASCII), PythonJson.dumpsBytes(value))
        }
    }

    @Test
    fun `key order separators and number rendering follow CPython defaults`() {
        val body = linkedMapOf<String, Any?>(
            "model" to "m", "max_tokens" to 8192,
            "messages" to listOf(linkedMapOf("role" to "system", "content" to "s"), linkedMapOf("role" to "user", "content" to "u"))
        )
        assertEquals("""{"model": "m", "max_tokens": 8192, "messages": [{"role": "system", "content": "s"}, {"role": "user", "content": "u"}]}""", PythonJson.dumps(body))
        body["temperature"] = 0.0
        assertTrue(PythonJson.dumps(body).endsWith(""", "temperature": 0.0}"""))
        assertFalse(PythonJson.dumps(body).endsWith("\n"))
        assertEquals("0.0", PythonJson.pythonFloatRepr(0.0))
        assertEquals("0.7", PythonJson.pythonFloatRepr(0.7))
        assertEquals("1.0", PythonJson.pythonFloatRepr(1.0))
        assertEquals("1e-05", PythonJson.pythonFloatRepr(1e-5))
        assertEquals("1e+16", PythonJson.pythonFloatRepr(1e16))
        assertEquals("1000000000000000.0", PythonJson.pythonFloatRepr(1e15))
        assertEquals("0.0001", PythonJson.pythonFloatRepr(0.0001))
        assertEquals("123.456", PythonJson.pythonFloatRepr(123.456))
        assertEquals("-0.5", PythonJson.pythonFloatRepr(-0.5))
        assertEquals("2.5e-07", PythonJson.pythonFloatRepr(2.5e-7))
        assertEquals("1.5e+20", PythonJson.pythonFloatRepr(1.5e20))
    }

    @Test
    fun `non ascii is escaped as lowercase u escapes and astral characters as surrogate pairs`() {
        assertEquals("\"\\u2014\"", PythonJson.dumps("\u2014"))
        assertEquals("\"\\ud83d\\ude00\"", PythonJson.dumps("\uD83D\uDE00"))
        assertEquals("\"\\u007f\"", PythonJson.dumps("\u007f"))
        assertEquals("\"/\"", PythonJson.dumps("/"))
        assertEquals("\"\\u0000\\u001f\\b\\f\\n\\r\\t\"", PythonJson.dumps("\u0000\u001f\b\u000c\n\r\t"))
        assertThrows(IllegalArgumentException::class.java) { PythonJson.dumps(java.util.Date()) }
    }
}
