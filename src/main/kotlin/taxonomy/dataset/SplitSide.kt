package taxonomy.dataset

import kotlinx.serialization.Serializable
import java.math.BigInteger
import java.security.MessageDigest
import java.text.Normalizer

/** The three sides an item can have. Exactly one holds for every hash value in [0, [SplitSide.SIDE_MODULUS]). */
enum class Side { EVAL, GATE, TRAIN }

/**
 * The split side function, side = f(item) (docs/design/FRAMEWORK.md Stage 0; item 18
 * SPLIT-FUNCTION-IMPL).
 *
 * Kotlin half of a two-language, byte-identical function; the Python half is
 * tools/analysis/split_side.py. Every constant is a literal in exactly one place per language
 * and is pinned by experiment_configs/split_function_vectors.json (generated by the Python
 * module, asserted here by SplitSideVectorsTest, so the Kotlin test is the independent
 * replication). A normaliser change is a [NORMALISER_VERSION] bump, never a silent re-split.
 *
 * Tier (a), pinned corpora: EVAL iff the id is in the frozen list or the stem key equals a
 * pinned item's stem key (content closure); among the rest, GATE iff the side hash lands in
 * [[GATE_LOWER], [GATE_UPPER]); TRAIN otherwise. Pool ids stay hashes of id lists
 * ([ReservedPool.computePoolId]) and are never recomputed from content.
 *
 * Tier (b), items ingested after the pin: h = uint64(sha256(normaliser_version U+001F
 * (family_id ?: content_key))) mod [SIDE_MODULUS]; EVAL iff h < [EVAL_UPPER]; GATE iff
 * [GATE_LOWER] <= h < [GATE_UPPER]; TRAIN otherwise.
 */
object SplitSide {
    const val NORMALISER_VERSION = "norm-v1"
    const val KEY_RULE = "ck-v1"
    const val SIDE_MODULUS = 1000
    const val EVAL_UPPER = 300
    const val GATE_LOWER = 300
    const val GATE_UPPER = 400

    const val FIELD_SEP = "\u001f"
    const val OPTION_SEP = "\u001e"

    /** Explicit whitespace class, identical to split_side.WHITESPACE_CLASS; not the runtime's isWhitespace(). */
    const val WHITESPACE_CLASS = "[\\t\\n\\x0b\\x0c\\r \\x85\\xa0\\u1680\\u2000-\\u200a\\u2028\\u2029\\u202f\\u205f\\u3000]+"
    private val WS = Regex(WHITESPACE_CLASS)

    /** NFKC, ASCII-only case fold (A-Z -> a-z), whitespace runs -> one U+0020, trimmed. Idempotent. */
    fun norm(s: String): String {
        val nfkc = Normalizer.normalize(s, Normalizer.Form.NFKC)
        val folded = buildString(nfkc.length) {
            for (ch in nfkc) append(if (ch in 'A'..'Z') (ch + ('a' - 'A')) else ch)
        }
        return WS.replace(folded, " ").trim(' ')
    }

    private val UTF8_ORDER = Comparator<String> { a, b ->
        val x = a.toByteArray(Charsets.UTF_8)
        val y = b.toByteArray(Charsets.UTF_8)
        val n = minOf(x.size, y.size)
        for (i in 0 until n) {
            val d = (x[i].toInt() and 0xff) - (y[i].toInt() and 0xff)
            if (d != 0) return@Comparator d
        }
        x.size - y.size
    }

    private fun sha256(s: String): ByteArray = MessageDigest.getInstance("SHA-256").digest(s.toByteArray(Charsets.UTF_8))
    private fun hex(b: ByteArray): String = b.joinToString("") { "%02x".format(it) }

    /**
     * hex sha256 over norm(stem) U+001F (U+001E norm(option) for each sorted option) U+001F contractId.
     * Options sort by UTF-8 bytes (= code point order): the JVM's default String order is
     * UTF-16 code-unit order, which differs above U+FFFF.
     */
    fun contentKey(stem: String, options: List<String>, contractId: String): String {
        val opts = options.map { norm(it) }.sortedWith(UTF8_ORDER)
        // Each option is PREFIXED by the separator so [] and [""] differ and the encoding is injective.
        val payload = norm(stem) + FIELD_SEP + opts.joinToString("") { OPTION_SEP + it } + FIELD_SEP + contractId
        return hex(sha256(payload))
    }

    /** Options-free key, contentKey(text, [], ""): what the tree guard keys on (an embedding carries only its raw text). */
    fun stemKey(text: String): String = contentKey(text, emptyList(), "")

    /** uint64 of the first 8 big-endian bytes of sha256(normaliserVersion U+001F key), mod [SIDE_MODULUS]. */
    fun sideHash(key: String, normaliserVersion: String = NORMALISER_VERSION): Int {
        val d = sha256(normaliserVersion + FIELD_SEP + key)
        val u = BigInteger(1, d.copyOfRange(0, 8))
        return u.mod(BigInteger.valueOf(SIDE_MODULUS.toLong())).toInt()
    }

    /** Exactly one side for every h in [0, SIDE_MODULUS). */
    fun sideOfHash(h: Int): Side = when {
        h < EVAL_UPPER -> Side.EVAL
        GATE_LOWER <= h && h < GATE_UPPER -> Side.GATE
        else -> Side.TRAIN
    }

    /** Side of an item ingested after the pin. */
    fun tierB(familyId: String?, contentKey: String): Side =
        sideOfHash(sideHash(familyId?.takeIf { it.isNotEmpty() } ?: contentKey))

    /**
     * Side of an item of a pinned corpus: EVAL by id or by content closure, GATE by the hash
     * restricted to non-EVAL items, TRAIN otherwise.
     */
    fun tierA(pinnedIds: Set<Int>, pinnedStemKeys: Set<String>, id: Int, stemKey: String, familyId: String? = null): Side {
        if (id in pinnedIds || stemKey in pinnedStemKeys) return Side.EVAL
        val h = sideHash(familyId?.takeIf { it.isNotEmpty() } ?: stemKey)
        return if (GATE_LOWER <= h && h < GATE_UPPER) Side.GATE else Side.TRAIN
    }

    /** The GATE slice of a TRAIN-side id -> text map: ids whose stem-key hash lands in [GATE_LOWER, GATE_UPPER). */
    fun gateOf(trainIdToText: Map<Int, String>): Set<Int> =
        trainIdToText.filterValues { text -> sideHash(stemKey(text)).let { GATE_LOWER <= it && it < GATE_UPPER } }.keys

    fun stamp(poolId: String?): FunctionStamp =
        FunctionStamp(NORMALISER_VERSION, KEY_RULE, SIDE_MODULUS, EVAL_UPPER, GATE_LOWER, GATE_UPPER, poolId)
}

/**
 * The identity of the split function, written into every artefact that depends on it (the
 * diagnostics manifest, the snapshot settings, gate_ids.json), so a future normaliser change is
 * a version mismatch at re-derivation and never a silent re-split.
 */
@Serializable
data class FunctionStamp(
    val normaliserVersion: String,
    val keyRule: String,
    val modulus: Int,
    val evalUpper: Int,
    val gateLower: Int,
    val gateUpper: Int,
    val poolId: String? = null
) {
    /** Same function, possibly a different pool. */
    fun sameFunctionAs(other: FunctionStamp): Boolean =
        normaliserVersion == other.normaliserVersion && keyRule == other.keyRule && modulus == other.modulus &&
            evalUpper == other.evalUpper && gateLower == other.gateLower && gateUpper == other.gateUpper
}

/**
 * Typed hook for a future epoch gate (RESOLVE section 6 rule 7): its only input type is the
 * GATE slice, so it cannot be handed EVAL by construction. The batch loop has no held-out gate
 * today, so the default is a no-op that accepts every commit; implementing the gate is a
 * separate item.
 */
fun interface EpochGate {
    fun accept(gateIds: Set<Int>): Boolean

    companion object {
        val NONE: EpochGate = EpochGate { true }
    }
}
